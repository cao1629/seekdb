    def trial(self, files):
        for f in files:
            key = f
            print("=" * 100)
            print("FILE %s  unit=%s  live=%s  contexts=%s  forwarder=%s" % (
                key, self.unit_of.get(key), key in self.live, sorted(self.visits.get(key, ())),
                self.forwarder_target.get(key, self.umbrella.get(key, "-"))))
            _, includes, _, _ = self.scan_one(key)
            for idx, (line, quoted, spelling, dead, conds) in enumerate(includes):
                res = sorted({(klass, self.display(t) if t else "-")
                              for _, klass, t in self.results.get((key, idx), ())})
                sp = ("\"%s\"" if quoted else "<%s>") % spelling
                print("  L%-5d %-60s %s%s%s" % (line, sp, "DEAD(#if 0) " if dead else "",
                                                 " ; ".join("%s %s" % r for r in res),
                                                 ("   {%s}" % " && ".join(conds)) if conds else ""))
            width = lambda kind: 120 if kind == "include" else 400
            print("  edges out:")
            for (a, b, kind) in sorted(self.edges):
                if a == key:
                    print("    %-14s %s  [%s]" % (kind, b, "; ".join(self.edges[(a, b, kind)])[:width(kind)]))
            print("  edges in (definition, own-header, link):")
            for (a, b, kind) in sorted(self.edges):
                if b == key and kind in ("definition", "own-header", "link"):
                    print("    %-14s %s  [%s]" % (kind, a, "; ".join(self.edges[(a, b, kind)])[:width(kind)]))
            uid = self.unit_of.get(key)
            if uid:
                print("  unit %s = %s ; class key %s" % (uid, ",".join(self.units[uid]),
                                                        self.class_key(uid, self.units[uid])))


