def _lex_sub(m):
    s = m.group(0)
    c = s[0]
    if c == "/":
        return " " + "\n" * s.count("\n")
    if c == "R":
        return "\"\"" + "\n" * s.count("\n")
    return s


def scan_text(text, want_classes):
    clean = LEX_RE.sub(_lex_sub, text)
    includes = []
    stack = []
    pos = 0
    line = 1
    prev = None
    for m in DIRECTIVE_RE.finditer(clean):
        line += clean.count("\n", pos, m.start())
        pos = m.start()
        d = m.group(1)
        rest = " ".join(m.group(2).split())
        if d == "define" and prev is not None and prev[0] == "ifndef" and stack and rest.split(" ")[0] == prev[1]:
            stack[-1][3] = True
        prev = (d, rest)
        if d in ("if", "ifdef", "ifndef"):
            if d == "if":
                cond = rest
                lit = rest if rest in ("0", "1") else None
            else:
                cond = ("defined(%s)" if d == "ifdef" else "!defined(%s)") % rest
                lit = None
            stack.append([cond, lit == "0", lit, False])
        elif d == "elif":
            if stack:
                f = stack[-1]
                if f[2] == "1":
                    f[1] = True
                else:
                    f[1] = rest == "0"
                    if rest == "1":
                        f[2] = "1"
                f[0] = rest
        elif d == "else":
            if stack:
                f = stack[-1]
                f[1] = f[2] == "1"
                f[0] = "!(%s)" % f[0]
        elif d == "endif":
            if stack:
                stack.pop()
        elif d in ("include", "include_next", "import"):
            am = INCLUDE_ARG_RE.match(rest)
            if am:
                dead = any(f[1] for f in stack)
                conds = tuple(f[0] for f in stack if not f[3])
                includes.append((line, am.group(1) is not None, am.group(1) or am.group(2), dead, conds))
    forwarder = False
    classes = []
    if want_classes:
        classes = CLASS_RE.findall(clean)
        if includes and len(clean) < 20000:
            forwarder = all(FORWARDER_LINE_RE.match(l) for l in clean.split("\n") if l.strip())
    return includes, forwarder, classes


def is_ident(t):
    return t[0].isalpha() or t[0] == "_"


def _proto_lex_sub(m):
    s = m.group(0)
    c = s[0]
    if c == "/":
        return " " + "\n" * s.count("\n")
    if c == "R":
        return "\"\"" + "\n" * s.count("\n")
    if c == "\"":
        return s if s in ("\"C\"", "\"C++\"") else "\"\"" + "\n" * s.count("\n")
    return "''" + "\n" * s.count("\n")


def balanced(tokens):
    stack = []
    cut = 0
    for k, t in enumerate(tokens):
        if t == "(":
            stack.append(k)
        elif t == ")":
            if stack:
                stack.pop()
            else:
                cut = k + 1
    if stack:
        cut = max(cut, stack[-1] + 1)
    return tokens[cut:]


def skip_group(tokens, k, open_t, close_t):
    depth = 0
    while k < len(tokens):
        if tokens[k] == open_t:
            depth += 1
        elif tokens[k] == close_t:
            depth -= 1
            if depth == 0:
                return k + 1
        k += 1
    return k


def top_groups(tokens):
    groups = []
    depth = 0
    start = 0
    for k, t in enumerate(tokens):
        if t == "(":
            if depth == 0:
                start = k
            depth += 1
        elif t == ")":
            depth -= 1
            if depth == 0:
                groups.append((start, k))
    return groups


def split_top(tokens):
    parts = []
    cur = []
    depth = 0
    for t in tokens:
        if t in ("<", "[", "("):
            depth += 1
        elif t in (">", "]", ")"):
            depth -= 1
        if t == "," and depth == 0:
            parts.append(cur)
            cur = []
        else:
            cur.append(t)
    parts.append(cur)
    return parts


def strip_leading_macros(tokens):
    while len(tokens) > 2 and is_ident(tokens[0]) and tokens[0].isupper() and tokens[1] == "(":
        k = skip_group(tokens, 1, "(", ")")
        if k >= len(tokens):
            break
        tokens = tokens[k:]
    return tokens


def declarator(tokens):
    groups = top_groups(tokens)
    for gi in range(len(groups) - 1, -1, -1):
        s, e = groups[gi]
        if s == 0:
            continue
        name = tokens[s - 1]
        if not is_ident(name) or name in PAREN_KEYWORDS or (gi > 0 and name.isupper()):
            continue
        if s + 1 < e and tokens[s + 1] in ("*", "&", "^"):
            continue
        if s >= 2 and tokens[s - 2] in ("::", "~", "operator", ".", "->"):
            return None
        before = tokens[:s - 1]
        if not specifiers_ok(before):
            return None
        if not any(is_ident(t) for t in before):
            return None
        return s - 1, s, e
    return None


def specifiers_ok(before):
    depth = 0
    angle = 0
    for k, t in enumerate(before):
        if t == "(":
            if depth == 0 and not (k > 0 and before[k - 1] in PAREN_KEYWORDS):
                return False
            depth += 1
        elif t == ")":
            depth -= 1
        elif depth == 0 and t == "<":
            angle += 1
        elif depth == 0 and t == ">":
            angle -= 1
        elif depth == 0 and (t in EXPR_TOKENS or (t == "," and angle <= 0)):
            return False
    return True


def param_type(p):
    toks = []
    k = 0
    while k < len(p):
        t = p[k]
        if t in ("__attribute__", "alignas", "__declspec") and k + 1 < len(p) and p[k + 1] == "(":
            k = skip_group(p, k + 1, "(", ")")
            continue
        if t == "[" and k + 1 < len(p) and p[k + 1] == "[":
            k = skip_group(p, k, "[", "]")
            continue
        toks.append(t)
        k += 1
    if toks == ["..."]:
        return "..."
    named = False
    for s, e in top_groups(toks):
        inner = toks[s + 1:e]
        if inner and (inner[0] in ("*", "&", "^") or ("::" in inner and "*" in inner)):
            idx = [j for j in range(s + 1, e) if is_ident(toks[j]) and toks[j] not in CV_WORDS]
            if idx and toks[idx[-1] - 1] in ("*", "&", "^", "const", "volatile"):
                toks = toks[:idx[-1]] + toks[idx[-1] + 1:]
            named = True
            break
    if not named:
        cut = len(toks)
        depth = 0
        for j, t in enumerate(toks):
            if t in ("(", "<"):
                depth += 1
            elif t in (")", ">"):
                depth -= 1
            elif t == "[" and depth == 0:
                cut = j
                break
        head = toks[:cut]
        arrays = sum(1 for t in toks[cut:] if t == "[")
        if len(head) >= 2 and is_ident(head[-1]) and head[-1] not in BUILTIN_TYPES | CV_WORDS | ELABORATED_WORDS \
                and head[-2] != "::" and any(t in ("*", "&", ">") or (is_ident(t) and t not in CV_WORDS | ELABORATED_WORDS)
                                             for t in head[:-1]):
            head = head[:-1]
        toks = head + ["*"] * arrays
    out = []
    k = 0
    while k < len(toks):
        t = toks[k]
        if t in ELABORATED_WORDS or t == "::":
            k += 1
            continue
        if is_ident(t) and k + 1 < len(toks) and toks[k + 1] == "::":
            k += 2
            continue
        out.append(t)
        k += 1
    if not any(t in ("*", "&", "(", "[") for t in out):
        out = [t for t in out if t not in CV_WORDS]
    elif "*" in out:
        last = max(j for j, t in enumerate(out) if t == "*")
        out = out[:last + 1] + [t for t in out[last + 1:] if t not in CV_WORDS]
    return " ".join(out)


def param_sig(params):
    if not params or params == ["void"]:
        return ()
    out = []
    for p in split_top(params):
        depth = 0
        for k, t in enumerate(p):
            if t in ("(", "[", "<"):
                depth += 1
            elif t in (")", "]", ">"):
                depth -= 1
            elif t == "=" and depth == 0:
                p = p[:k]
                break
        out.append(param_type(p))
    return tuple(out)


def skip_angle(tokens, k):
    depth = 0
    while k < len(tokens):
        t = tokens[k]
        if t == "<":
            if depth > 0 and k + 1 < len(tokens) and tokens[k + 1] == "<":
                k += 2
                continue
            depth += 1
        elif t == ">":
            depth -= 1
            if depth == 0:
                return k + 1
        elif t == "(":
            k = skip_group(tokens, k, "(", ")")
            continue
        k += 1
    return k


def skip_prefix(tokens):
    k = 0
    while k < len(tokens):
        if tokens[k] == "template" and k + 1 < len(tokens) and tokens[k + 1] == "<":
            k = skip_angle(tokens, k + 1)
        elif tokens[k] == "[" and k + 1 < len(tokens) and tokens[k + 1] == "[":
            k = skip_group(tokens, k, "[", "]")
        else:
            break
    return tokens[k:]


def class_head(text):
    tokens = TOKEN_RE.findall(text)
    while True:
        tokens = strip_leading_macros(skip_prefix(tokens))
        if len(tokens) > 1 and tokens[0] in ACCESS_WORDS and tokens[1] == ":":
            tokens = tokens[2:]
            continue
        break
    k = 1 if tokens and tokens[0] == "typedef" else 0
    if k >= len(tokens) or tokens[k] not in ("class", "struct", "union"):
        return None
    k += 1
    words = []
    while k < len(tokens):
        t = tokens[k]
        if t == "[" and k + 1 < len(tokens) and tokens[k + 1] == "[":
            k = skip_group(tokens, k, "[", "]")
            continue
        if not is_ident(t):
            break
        if k + 1 < len(tokens) and tokens[k + 1] == "(":
            if not (t.isupper() or t in PAREN_KEYWORDS):
                return None
            k = skip_group(tokens, k + 1, "(", ")")
            continue
        name = [t]
        k += 1
        while k + 1 < len(tokens) and tokens[k] == "::" and is_ident(tokens[k + 1]):
            name.append(tokens[k + 1])
            k += 2
        if k < len(tokens) and tokens[k] == "<":
            k = skip_angle(tokens, k)
        words.append("::".join(name))
    if k < len(tokens) and tokens[k] != ":":
        return None
    while words and words[-1] == "final":
        words.pop()
    if not words or any(not w.isupper() for w in words[:-1]):
        return None
    return words[-1]


def parse_qualified(text, mode):
    tokens = strip_leading_macros(skip_prefix(balanced(TOKEN_RE.findall(text))))
    if not tokens or tokens[0] in LEAD_REJECT or tokens[0] == "extern":
        return None
    name_at = end = None
    angle = 0
    k = 0
    while k < len(tokens):
        t = tokens[k]
        if t == "operator":
            j = k + 1
            if j + 1 < len(tokens) and tokens[j] == "(" and tokens[j + 1] == ")":
                j += 2
            while j < len(tokens) and tokens[j] != "(":
                j += 1
            if angle == 0 and mode == "function" and j < len(tokens):
                name_at, end = k, j
            break
        if t == "<":
            angle += 1
        elif t == ">":
            angle = max(0, angle - 1)
        elif angle == 0 and mode != "function" and t in ("=", "[", "("):
            name_at, end = k - 1, k
            break
        elif t == "(":
            if angle == 0 and mode == "function" and k > 0 and is_ident(tokens[k - 1]) \
                    and tokens[k - 1] not in PAREN_KEYWORDS:
                name_at, end = k - 1, k
                break
            k = skip_group(tokens, k, "(", ")")
            continue
        k += 1
    if name_at is None and mode != "function" and angle == 0:
        name_at, end = len(tokens) - 1, len(tokens)
    if name_at is None or name_at < 0:
        return None
    if tokens[name_at] == "operator":
        op = tokens[name_at + 1:end]
        name = "operator " + " ".join(op) if op and is_ident(op[0]) else "operator" + "".join(op)
    elif is_ident(tokens[name_at]):
        name = tokens[name_at]
    else:
        return None
    j = name_at - 1
    if j >= 0 and tokens[j] == "~":
        name = "~" + name
        j -= 1
    qual = []
    while j >= 1 and tokens[j] == "::":
        q = j - 1
        if tokens[q] == ">":
            depth = 0
            while q >= 0:
                if tokens[q] == ">":
                    depth += 1
                elif tokens[q] == "<":
                    depth -= 1
                    if depth == 0:
                        break
                q -= 1
            q -= 1
        if q < 0 or not is_ident(tokens[q]) or tokens[q] in BUILTIN_TYPES | QUALIFIER_WORDS or tokens[q] == "operator":
            break
        qual.insert(0, tokens[q])
        j = q - 1
    if not qual:
        return None
    glob = j >= 0 and tokens[j] == "::"
    before = tokens[:j] if glob else tokens[:j + 1]
    special = name.lstrip("~") == qual[-1] or name.startswith("operator")
    if not special and not any(is_ident(t) for t in before):
        return None
    if not specifiers_ok(before):
        return None
    if mode != "function":
        return tuple(qual), name, glob, "variable", None
    close = skip_group(tokens, end, "(", ")")
    rest = tokens[close:]
    if ":" not in rest and not trailing_ok(rest, DEF_TRAILING):
        return None
    return tuple(qual), name, glob, "function", param_sig(tokens[end + 1:close - 1])


def trailing_ok(rest, allowed):
    j = 0
    while j < len(rest):
        t = rest[j]
        if t == "(":
            j = skip_group(rest, j, "(", ")")
            continue
        if t in allowed or (is_ident(t) and t != "try"):
            j += 1
            continue
        return False
    return True


def parse_statement(text, is_def):
    tokens = balanced(TOKEN_RE.findall(text))
    linkage = None
    lead = []
    k = 0
    while k < len(tokens):
        t = tokens[k]
        if t == "extern" and k + 1 < len(tokens) and tokens[k + 1] in ("\"C\"", "\"C++\""):
            linkage = tokens[k + 1].strip("\"")
            lead.append("extern")
            k += 2
            continue
        if t == "[" and k + 1 < len(tokens) and tokens[k + 1] == "[":
            k = skip_group(tokens, k, "[", "]")
            continue
        break
    tokens = strip_leading_macros(lead + tokens[k:])
    if not tokens or tokens[0] in LEAD_REJECT:
        return None
    if tokens[0] in ("class", "struct", "union", "enum") and "(" not in tokens:
        return None
    d = declarator(tokens)
    if d is None:
        if is_def or tokens[0] != "extern" or "=" in tokens or "{" in tokens:
            return None
        if "(" in tokens:
            v = pointer_variable(tokens)
            return [("variable", v, linkage, "static" in tokens, None)] if v else None
        parts = split_top(tokens[1:])
        if len(parts[0]) < 2:
            return None
        names = []
        for p in parts:
            p = list(p)
            while p and p[-1] == "]":
                depth = 0
                while p:
                    t = p.pop()
                    if t == "]":
                        depth += 1
                    elif t == "[":
                        depth -= 1
                        if depth == 0:
                            break
            if p and is_ident(p[-1]) and p[-1] not in QUALIFIER_WORDS:
                names.append(p[-1])
        return [("variable", n, linkage, "static" in tokens, None) for n in names] or None
    ni, s, e = d
    rest = tokens[e + 1:]
    if any("alias" in t.lower() for t in rest):
        return None
    if is_def:
        if ":" in rest or "=" in rest or not trailing_ok(rest, DEF_TRAILING):
            return None
    else:
        if rest and rest[0] == "=":
            if len(rest) != 2 or rest[1] not in ("0", "default", "delete"):
                return None
        elif not trailing_ok(rest, DECL_TRAILING):
            return None
        params = tokens[s + 1:e]
        if any(t in ARGUMENT_TOKENS for t in params):
            return None
        depth = 0
        for t in params:
            if t == "[":
                depth += 1
            elif t == "]":
                depth -= 1
            elif depth == 0 and t[0].isdigit():
                return None
    before = tokens[:ni]
    internal = any(t in INTERNAL_WORDS for t in before)
    return [("function", tokens[ni], linkage, internal, param_sig(tokens[s + 1:e]))]


def pointer_variable(tokens):
    for s, e in top_groups(tokens):
        inner = tokens[s + 1:e]
        j = 0
        while j < len(inner) and inner[j] in ("*", "&", "^", "const"):
            j += 1
        if j and j + 1 == len(inner) and is_ident(inner[j]):
            return inner[j]
        return None
    return None


def parse_variable_def(text, is_c):
    tokens = balanced(TOKEN_RE.findall(text))
    k = 0
    while k < len(tokens) and tokens[k] == "[" and k + 1 < len(tokens) and tokens[k + 1] == "[":
        k = skip_group(tokens, k, "[", "]")
    tokens = strip_leading_macros(tokens[k:])
    if not tokens or tokens[0] in LEAD_REJECT or tokens[0] == "extern":
        return None
    first = split_top(tokens)[0]
    depth = 0
    cut = len(first)
    for k, t in enumerate(first):
        if t == "<":
            depth += 1
        elif t == ">":
            depth -= 1
        elif depth == 0 and t in ("=", "[", "(", "{"):
            cut = k
            break
    if cut < len(first) and first[cut] == "(" and cut + 1 < len(first) and first[cut + 1] in ("*", "&", "^"):
        j = cut + 1
        while j < len(first) and first[j] in ("*", "&", "^", "const"):
            j += 1
        if j >= len(first) or not is_ident(first[j]):
            return None
        name, before = first[j], first[:cut]
    else:
        if cut < 1:
            return None
        name, before = first[cut - 1], first[:cut - 1]
        if cut >= 2 and first[cut - 2] in ("::", ".", "->", "~"):
            return None
    if not is_ident(name) or name in QUALIFIER_WORDS or name in PAREN_KEYWORDS or name in BUILTIN_TYPES \
            or "operator" in before or ":" in before:
        return None
    if not any(is_ident(t) and t not in ("struct", "class", "union", "enum", "typename") and t not in QUALIFIER_WORDS
               for t in before):
        return None
    internal = any(t in INTERNAL_WORDS for t in before)
    const_only = False
    if not is_c and not internal:
        last_ptr = max((k for k, t in enumerate(before) if t in ("*", "&")), default=-1)
        const_only = "const" in before[last_ptr + 1:]
    return name, internal, const_only


def scan_protos(text, is_c, want_uses):
    clean = PROTO_LEX_RE.sub(_proto_lex_sub, text)
    events = []
    parts = []
    last = 0
    for m in PP_RE.finditer(clean):
        events.append((m.start(), 1, m.group(1), " ".join(m.group(2).split())))
        parts.append(clean[last:m.start()])
        parts.append(BLANK_RE.sub(" ", m.group(0)))
        last = m.end()
    parts.append(clean[last:])
    code = "".join(parts)
    for m in DELIM_RE.finditer(code):
        events.append((m.start(), 0, m.group(0), None))
    events.sort()
    nl = [m.start() for m in re.finditer("\n", code)]
    frames = []
    pp = []
    dead = False
    stmt_start = 0
    decls = []
    defs = []
    qdefs = []
    classes = []
    spans = []
    conds = []
    prev = None
    base_linkage = "C" if is_c else "C++"

    def line_of(p):
        return bisect.bisect_left(nl, p) + 1

    def scope(block_ok):
        path = []
        linkage = base_linkage
        anon = False
        for kind, name in frames:
            if kind == "ns":
                path.append(name)
            elif kind == "anon":
                anon = True
            elif kind == "link":
                linkage = name
            elif not block_ok:
                return None
        return "::".join(path), linkage, anon

    def class_scope():
        path = []
        for kind, name in frames:
            if kind in ("ns", "class"):
                path.append(name)
            elif kind != "link":
                return None
        return path

    def record(start, end, is_def, st, variable_def=False):
        text = code[start:end]
        res = parse_statement(text, is_def)
        const_only = False
        if not res and variable_def:
            v = parse_variable_def(text, is_c)
            if v:
                res = [("variable", v[0], None, v[1], None)]
                const_only = v[2]
                is_def = True
        path, linkage, anon = st
        if not res:
            if (is_def or variable_def) and not is_c and not anon:
                q = parse_qualified(text, "variable" if variable_def else "function")
                if q:
                    qual, name, glob, kind, sig = q
                    word = "operator" if name.startswith("operator") else re.match(r"~?(\w+)", name).group(1)
                    m = re.search(r"::\s*~?\s*(%s)\b" % re.escape(word), text)
                    qdefs.append((start + (m.start(1) if m else 0), linkage, path, qual, name, kind, sig, glob))
            return
        for kind, name, lk, internal, sig in res:
            if internal or anon:
                continue
            m = re.search(r"\b%s\b" % re.escape(name), text)
            p = start + (m.start() if m else 0)
            lk = lk or linkage
            if is_def:
                defs.append((p, lk, "" if lk == "C" else path, name, kind, sig, const_only))
            else:
                decls.append((line_of(p), lk, "" if lk == "C" else path, name, kind, sig))
            if not const_only:
                spans.append((start, end))

    for pos, kind, d, arg in events:
        if kind == 1:
            if d == "define" and prev is not None and prev[0] == "ifndef" and pp and arg.split(" ")[0] == prev[1]:
                pp[-1][6] = True
            prev = (d, arg)
            if d in ("if", "ifdef", "ifndef"):
                pp.append([list(frames), dead, d == "if" and arg == "1", not code[stmt_start:pos].strip(), pos,
                           arg if d == "if" else ("defined(%s)" if d == "ifdef" else "!defined(%s)") % arg, False])
                dead = dead or (d == "if" and arg == "0")
            elif d in ("elif", "else") and pp:
                top = pp[-1]
                conds.append((top[4], pos, top[5], top[6]))
                frames = list(top[0])
                if d == "else":
                    branch_dead = top[2]
                    top[5] = "!(%s)" % top[5]
                else:
                    branch_dead = top[2] or arg == "0"
                    top[2] = top[2] or arg == "1"
                    top[5] = arg
                top[4] = pos
                dead = top[1] or branch_dead
                if top[3]:
                    stmt_start = pos
            elif d == "endif" and pp:
                top = pp.pop()
                conds.append((top[4], pos, top[5], top[6]))
                dead = top[1]
            continue
        if dead:
            continue
        if d == "{":
            tail = code[stmt_start:pos]
            m = NAMESPACE_RE.search(tail) if "namespace" in tail else None
            lm = LINKAGE_RE.search(tail) if "extern" in tail else None
            cname = class_head(tail) if not m and not lm and CLASS_WORD_RE.search(tail) else None
            if m:
                frames.append(("ns", m.group(1)) if m.group(1) else ("anon", None))
            elif lm:
                frames.append(("link", lm.group(1)))
            elif cname:
                cp = class_scope()
                if cp is not None:
                    cm = re.search(r"\b%s\b" % re.escape(cname.split("::")[-1]), tail)
                    classes.append((line_of(stmt_start + (cm.start() if cm else 0)), "::".join(cp + [cname])))
                frames.append(("class", cname))
            else:
                if "(" in tail or tail.rstrip().endswith("="):
                    st = scope(False)
                    if st is not None:
                        record(stmt_start, pos, True, st, tail.rstrip().endswith("="))
                frames.append(("block", None))
            stmt_start = pos + 1
        elif d == "}":
            if frames:
                frames.pop()
            stmt_start = pos + 1
        else:
            st = scope(False)
            if st is not None:
                record(stmt_start, pos, False, st, True)
            else:
                seg = code[stmt_start:pos]
                if "extern" in seg and seg.lstrip().startswith("extern"):
                    record(stmt_start, pos, False, scope(True))
            stmt_start = pos + 1

    def cond_at(p):
        inner = None
        for a, b, c, guard in conds:
            if not guard and a <= p < b and (inner is None or a >= inner[0]):
                inner = (a, b, c)
        return inner[2] if inner else ""

    out = []
    if want_uses:
        for name in sorted({r[3] for r in decls}):
            uses = [m.start() for m in re.finditer(r"\b%s\b" % re.escape(name), clean)
                    if not any(a <= m.start() < b for a, b in spans)]
            cond_use = None
            for p in uses:
                inner = None
                for a, b, c, _ in conds:
                    if a <= p < b and (inner is None or a >= inner[0]):
                        inner = (a, b, c)
                if inner is not None:
                    cond_use = (line_of(p), inner[2])
                    break
            for r in decls:
                if r[3] == name:
                    out.append(r + (len(uses), cond_use))
    else:
        out = [r + (None, None) for r in decls]
    out_defs = [(line_of(p), lk, path, name, kind, sig, cond_at(p), const_only)
                for p, lk, path, name, kind, sig, const_only in defs]
    out_qdefs = [(line_of(p), lk, path, qual, name, kind, sig, glob, cond_at(p))
                 for p, lk, path, qual, name, kind, sig, glob in qdefs]
    return out, out_defs, out_qdefs, classes


def scan_file(args):
    path, want_classes, want_protos, want_uses = args
    with open(path, "rb") as f:
        data = f.read()
    text = data.decode("latin-1")
    includes, forwarder, classes = scan_text(text, want_classes)
    protos = scan_protos(text, path.endswith(".c"), want_uses) if want_protos else None
    return path, count_lines(data), includes, forwarder, classes, protos


def uleb(b, i):
    r = 0
    s = 0
    while True:
        c = b[i]
        i += 1
        r |= (c & 0x7f) << s
        if c < 0x80:
            return r, i
        s += 7


def macho_sections(data):
    if len(data) < 32 or struct.unpack_from("<I", data, 0)[0] != 0xfeedfacf:
        return {}
    ncmds = struct.unpack_from("<I", data, 16)[0]
    off = 32
    secs = {}
    for _ in range(ncmds):
        cmd, cmdsize = struct.unpack_from("<II", data, off)
        if cmd == 0x19:
            nsects = struct.unpack_from("<I", data, off + 64)[0]
            so = off + 72
            for _ in range(nsects):
                name = data[so:so + 16].rstrip(b"\0").decode("latin-1")
                size, offset = struct.unpack_from("<QI", data, so + 40)
                secs[name] = data[offset:offset + size]
                so += 80
        off += cmdsize
    return secs


def parse_abbrev(b, off):
    table = {}
    i = off
    while True:
        code, i = uleb(b, i)
        if code == 0:
            return table
        tag, i = uleb(b, i)
        children = b[i]
        i += 1
        attrs = []
        while True:
            at, i = uleb(b, i)
            fm, i = uleb(b, i)
            if at == 0 and fm == 0:
                break
            if fm == 0x21:
                _, i = uleb(b, i)
            attrs.append((at, fm))
        size = sum(FIXED_FORMS[fm] for _, fm in attrs) if all(fm in FIXED_FORMS for _, fm in attrs) else -1
        wanted = tag in SCOPE_TAGS or any(at in (AT_SPEC, AT_DECLARATION, AT_STMT_LIST) for at, _ in attrs) or (
            tag in (TAG_SUBPROGRAM, TAG_VARIABLE) and any(at == AT_DECL_FILE for at, _ in attrs))
        table[code] = (tag, children, attrs, size, wanted)


def skip_attrs(info, i, attrs):
    for _, fm in attrs:
        sz = FIXED_FORMS.get(fm)
        if sz is not None:
            i += sz
        elif fm in (0x18, 0x09):
            ln, i = uleb(info, i)
            i += ln
        elif fm in (0x0f, 0x15):
            _, i = uleb(info, i)
        elif fm == 0x0d:
            while info[i] & 0x80:
                i += 1
            i += 1
        elif fm == 0x08:
            i = info.index(b"\0", i) + 1
        elif fm == 0x0a:
            i += 1 + info[i]
        elif fm == 0x03:
            i += 2 + struct.unpack_from("<H", info, i)[0]
        elif fm == 0x04:
            i += 4 + struct.unpack_from("<I", info, i)[0]
        else:
            raise ValueError("unsupported DWARF form 0x%x" % fm)
    return i


def read_attr(info, i, fm, strs):
    sz = FIXED_FORMS.get(fm)
    if sz is not None:
        if fm == 0x0e:
            o = struct.unpack_from("<I", info, i)[0]
            return strs[o:strs.index(b"\0", o)].decode("latin-1"), i + 4
        if sz == 1:
            return info[i], i + 1
        if sz == 2:
            return struct.unpack_from("<H", info, i)[0], i + 2
        if sz == 4:
            return struct.unpack_from("<I", info, i)[0], i + 4
        if sz == 8:
            return struct.unpack_from("<Q", info, i)[0], i + 8
        return True, i + sz
    if fm == 0x08:
        e = info.index(b"\0", i)
        return info[i:e].decode("latin-1"), e + 1
    if fm in (0x0f, 0x15):
        return uleb(info, i)
    return None, skip_attrs(info, i, [(0, fm)])


def line_table_files(line, off):
    ver = struct.unpack_from("<H", line, off + 4)[0]
    if ver > 4:
        raise ValueError("unsupported line table version %d" % ver)
    i = off + 10 + (1 if ver >= 4 else 0) + 3
    opcode_base = line[i]
    i += opcode_base
    dirs = [""]
    while line[i] != 0:
        e = line.index(b"\0", i)
        dirs.append(line[i:e].decode("latin-1"))
        i = e + 1
    i += 1
    files = [None]
    while line[i] != 0:
        e = line.index(b"\0", i)
        name = line[i:e].decode("latin-1")
        i = e + 1
        d, i = uleb(line, i)
        _, i = uleb(line, i)
        _, i = uleb(line, i)
        files.append(posixpath.join(dirs[d], name) if d else name)
    return files


def strip_template_args(s):
    out = []
    depth = 0
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif depth == 0:
            out.append(ch)
    return "".join(out)


