def macho_symbols(data):
    undefined = set()
    strong = set()
    if len(data) < 32 or struct.unpack_from("<I", data, 0)[0] != 0xfeedfacf:
        return undefined, strong
    ncmds = struct.unpack_from("<I", data, 16)[0]
    off = 32
    for _ in range(ncmds):
        cmd, cmdsize = struct.unpack_from("<II", data, off)
        if cmd == 0x2:
            symoff, nsyms, stroff, _ = struct.unpack_from("<IIII", data, off + 8)
            for strx, typ, _, desc, _ in struct.iter_unpack("<IBBHQ", data[symoff:symoff + 16 * nsyms]):
                kind = typ & 0xef
                if kind == 0x01 or (kind == 0x0f and not desc & 0x0080):
                    s = stroff + strx
                    name = data[s:data.index(b"\0", s)].decode("latin-1")
                    (undefined if kind == 0x01 else strong).add(name[1:] if name.startswith("_") else name)
        off += cmdsize
    return undefined, strong


def dwarf_object(path):
    with open(path, "rb") as f:
        data = f.read()
    secs = macho_sections(data)
    undefined, strong = macho_symbols(data)
    info = secs.get("__debug_info")
    abbrev = secs.get("__debug_abbrev")
    strs = secs.get("__debug_str", b"")
    line = secs.get("__debug_line")
    pairs = set()
    classes = set()
    seen = set()
    ns_decls = set()
    ns_defs = set()
    sites = set()
    if not info or not abbrev or not line:
        return path, pairs, classes, seen, ns_decls, ns_defs, undefined, sites
    pos = 0
    while pos < len(info):
        unit_len, ver, aoff = struct.unpack_from("<IHI", info, pos)
        if ver > 4:
            raise ValueError("unsupported DWARF version %d in %s" % (ver, path))
        end = pos + 4 + unit_len
        table = parse_abbrev(abbrev, aoff)
        i = pos + 11
        stack = []
        kinds = []
        nested = 0
        incode = 0
        files = []
        decls = {}
        defs = []
        while i < end:
            die = i - pos
            code, i = uleb(info, i)
            if code == 0:
                if stack:
                    stack.pop()
                    k = kinds.pop()
                    if k != SCOPE_NS:
                        nested -= 1
                    if k == SCOPE_CODE:
                        incode -= 1
                continue
            tag, children, attrs, size, wanted = table[code]
            if not wanted or (incode and tag == TAG_VARIABLE):
                i = i + size if size >= 0 else skip_attrs(info, i, attrs)
                if children:
                    stack.append(None)
                    kinds.append(SCOPE_CODE)
                    nested += 1
                    incode += 1
                continue
            name = dfile = spec = link = origin = None
            dline = 0
            isdecl = external = False
            for at, fm in attrs:
                v, i = read_attr(info, i, fm, strs)
                if at == AT_NAME:
                    name = v
                elif at == AT_DECL_FILE:
                    dfile = v
                elif at == AT_DECL_LINE:
                    dline = v
                elif at == AT_SPEC:
                    spec = v
                elif at == AT_DECLARATION:
                    isdecl = True
                elif at == AT_EXTERNAL:
                    external = True
                elif at == AT_LINKAGE_NAME or at == AT_MIPS_LINKAGE_NAME:
                    link = v
                elif at == AT_ABSTRACT_ORIGIN:
                    origin = v
                elif at == AT_STMT_LIST and not files:
                    files = line_table_files(line, v)
                    seen.update(x for x in files if x and not x.startswith("/"))
            symbol = link or name if (external and not nested and tag in (TAG_SUBPROGRAM, TAG_VARIABLE)) else None
            if tag in (TAG_SUBPROGRAM, TAG_VARIABLE) and not isdecl and dline and dfile is not None \
                    and dfile < len(files) and not files[dfile].startswith("/"):
                sites.add((files[dfile], dline))
            if spec is not None and dfile is not None:
                defs.append((dfile, spec, dline))
            if isdecl and dfile is not None:
                decls[die] = (dfile, stack[:], name, symbol, "variable" if tag == TAG_VARIABLE else "function")
                if symbol and dfile < len(files) and not files[dfile].startswith("/"):
                    ns_decls.add((symbol, files[dfile], dline, "::".join(x for x in stack if x), name or ""))
            elif symbol and spec is None and origin is None and dfile is not None and dfile < len(files) \
                    and not files[dfile].startswith("/") and (ext_of(files[dfile]) in IMPL_EXTS or symbol in strong):
                ns_defs.add((symbol, files[dfile], dline, "::".join(x for x in stack if x), name or "",
                             "variable" if tag == TAG_VARIABLE else "function"))
            if tag in CLASS_TAGS and not isdecl and name and dfile is not None and dfile < len(files) \
                    and not files[dfile].startswith("/"):
                classes.add((files[dfile], strip_template_args("::".join([x for x in stack if x] + [name]))))
            if children:
                stack.append(name if tag in SCOPE_TAGS else None)
                if tag == TAG_NAMESPACE or tag == TAG_COMPILE_UNIT:
                    kinds.append(SCOPE_NS)
                else:
                    kinds.append(SCOPE_CLASS if tag in CLASS_TAGS else SCOPE_CODE)
                    nested += 1
                    if tag not in CLASS_TAGS:
                        incode += 1
        for dfile, spec, dline in defs:
            d = decls.get(spec)
            if d is None or dfile >= len(files) or d[0] >= len(files):
                continue
            a, b = files[dfile], files[d[0]]
            if d[3] and not a.startswith("/") and (ext_of(a) in IMPL_EXTS or d[3] in strong):
                ns_defs.add((d[3], a, dline, "::".join(x for x in d[1] if x), d[2] or "", d[4]))
            if a != b and not a.startswith("/") and not b.startswith("/"):
                scope = strip_template_args("::".join(x for x in d[1] if x))
                pairs.add((a, b, scope, d[2] or ""))
        pos = end
    return path, pairs, classes, seen, ns_decls, ns_defs, undefined, sites


class DisjointSet:
    def __init__(self, items):
        self.parent = {x: x for x in items}

    def find(self, x):
        root = x
        while self.parent[root] != root:
            root = self.parent[root]
        while self.parent[x] != root:
            self.parent[x], x = root, self.parent[x]
        return root

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            if rb < ra:
                ra, rb = rb, ra
            self.parent[rb] = ra


def tarjan(nodes, adj):
    index = {}
    low = {}
    on_stack = set()
    stack = []
    out = []
    counter = 0
    for start in nodes:
        if start in index:
            continue
        work = [(start, 0)]
        while work:
            node, pi = work[-1]
            if pi == 0:
                index[node] = low[node] = counter
                counter += 1
                stack.append(node)
                on_stack.add(node)
            succs = adj.get(node, ())
            recurse = False
            for k in range(pi, len(succs)):
                s = succs[k]
                if s not in index:
                    work[-1] = (node, k + 1)
                    work.append((s, 0))
                    recurse = True
                    break
                if s in on_stack:
                    low[node] = min(low[node], index[s])
            if recurse:
                continue
            if low[node] == index[node]:
                comp = []
                while True:
                    w = stack.pop()
                    on_stack.discard(w)
                    comp.append(w)
                    if w == node:
                        break
                out.append(sorted(comp))
            work.pop()
            if work:
                parent = work[-1][0]
                low[parent] = min(low[parent], low[node])
    return out


def condense(nodes, edges):
    adj = defaultdict(set)
    for a, b in edges:
        if a != b:
            adj[a].add(b)
    adj = {k: sorted(v) for k, v in adj.items()}
    comps = tarjan(sorted(nodes), adj)
    comp_of = {}
    for ci, comp in enumerate(comps):
        for n in comp:
            comp_of[n] = ci
    level = [0] * len(comps)
    for ci, comp in enumerate(comps):
        lv = 0
        for n in comp:
            for s in adj.get(n, ()):
                cj = comp_of[s]
                if cj != ci:
                    lv = max(lv, level[cj] + 1)
        level[ci] = lv
    return comps, comp_of, level


