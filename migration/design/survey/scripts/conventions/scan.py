def count(files, stripped):
    tot = collections.Counter()
    nfiles = collections.Counter()
    for f in files:
        try:
            t = read(f)
        except FileNotFoundError:
            continue
        if stripped:
            t = strip_code(t)
        for k, rx in P.items():
            c = len(rx.findall(t))
            if c:
                tot[k] += c
                nfiles[k] += 1
    return tot, nfiles


if __name__ == '__main__':
    allf = tracked_src_files()
    nodes = node_files()
    raw, rawf = count(allf, False)
    code, codef = count(nodes, True)
    print('# files: tracked src C/C++ =', len(allf), ' depmap nodes =', len(nodes))
    print('construct\traw_matches\traw_files\tcode_matches\tcode_files')
    for k in P:
        print(f'{k}\t{raw[k]}\t{rawf[k]}\t{code[k]}\t{codef[k]}')
